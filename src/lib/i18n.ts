export function translateCategory(name: string, lang: Language): string {
  if (!name || lang === 'vi') return name;
  if (CATEGORY_TRANSLATIONS[name]) {
    return CATEGORY_TRANSLATIONS[name][lang] || name;
  }
  return name;
}

export function translateWalletType(type: string, lang: Language): string {
  if (lang === 'en') {
    switch (type) {
      case 'CASH': return 'Cash';
      case 'BANK': return 'Bank Account';
      case 'CREDIT': return 'Credit Card';
      case 'SAVINGS': return 'Savings Account';
      default: return type;
    }
  } else if (lang === 'fr') {
    switch (type) {
      case 'CASH': return 'Espèces';
      case 'BANK': return 'Compte bancaire';
      case 'CREDIT': return 'Carte de crédit';
      case 'SAVINGS': return "Compte d'épargne";
      default: return type;
    }
  }
  switch (type) {
    case 'CASH': return 'Tiền mặt';
    case 'BANK': return 'Tài khoản ngân hàng';
    case 'CREDIT': return 'Thẻ tín dụng';
    case 'SAVINGS': return 'Tài khoản tiết kiệm';
    default: return type;
  }
}

