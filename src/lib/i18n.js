export function translateTag(tag, lang = 'vi') {
    if (!tag) return '';
    const clean = tag.replace(/^#/, '').trim();
    if (TAG_TRANSLATIONS[clean]) {
        return TAG_TRANSLATIONS[clean][lang] || (lang === 'vi' ? clean : TAG_TRANSLATIONS[clean].en || clean);
    }
    const lower = clean.toLowerCase();
    for (const [key, trans] of Object.entries(TAG_TRANSLATIONS)) {
        if (key.toLowerCase() === lower) {
            return trans[lang] || (lang === 'vi' ? trans.vi || key : trans.en || key);
        }
        if (trans.en && trans.en.toLowerCase() === lower) {
            return lang === 'vi' ? trans.vi || key : trans.en;
        }
        if (trans.vi && trans.vi.toLowerCase() === lower) {
            return lang === 'vi' ? trans.vi : trans.en;
        }
    }
    // Fallback: check if the tag matches a category translation
    const catTrans = translateCategory(clean, lang);
    if (catTrans && catTrans.toLowerCase() !== lower) {
        return catTrans;
    }
    return clean;
}

// Translate system-generated transaction notes (bill payments, goal deposits/withdrawals, transfers...). User-defined custom notes are preserved.
const NOTE_PATTERNS = [
    [/^Thanh toán hóa đơn: (.+)$/, (m) => `Bill payment: ${translateBillName(m[1], 'en')}`],
    [/^Tích lũy vào hũ: (.+)$/, (m) => `Saved to goal: ${m[1]}`],
    [/^Rút từ hũ tích lũy: (.+)$/, (m) => `Withdrawn from goal: ${m[1]}`],
    [/^Chuyển khoản từ (.+) sang (.+)$/, (m) => `Transfer from ${translateWalletName(m[1], 'en')} to ${translateWalletName(m[2], 'en')}`],
    [/^Thanh toán dư nợ thẻ (.+)$/, (m) => `Credit card payment: ${translateWalletName(m[1], 'en')}`],
    [/^Nạp từ (.+)$/, (m) => `Deposit from ${translateWalletName(m[1], 'en')}`],
    [/^Rút về (.+)$/, (m) => `Withdraw to ${translateWalletName(m[1], 'en')}`],
    [/^Sao kê ngân hàng$/, () => 'Bank statement'],
    [/^Chuyển khoản$/, () => 'Transfer'],
];
export function translateNote(note, lang = 'vi') {
    if (!note || lang !== 'en')
        return note || '';
    let text = String(note);
    // Suffix when deleting wallet that has transfer transactions
    let suffix = '';
    const deleted = text.match(/^(.*) \((từ|sang) ví đã xóa: (.*)\)$/);
    if (deleted) {
        text = deleted[1];
        suffix = ` (${deleted[2] === 'từ' ? 'from' : 'to'} deleted wallet: ${deleted[3]})`;
    }
    for (const [re, fn] of NOTE_PATTERNS) {
        const m = text.match(re);
        if (m)
            return fn(m) + suffix;
    }
    return text + suffix;
}

